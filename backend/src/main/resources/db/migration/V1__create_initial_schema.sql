CREATE TABLE skill_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);
CREATE TABLE skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES skill_category(id),
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    proficiency VARCHAR(20) NOT NULL CHECK (proficiency IN ('BEGINNER','INTERMEDIATE','ADVANCED','EXPERT')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL CHECK (type IN ('PROFESSIONAL','PROJECT','DEMO','CODE','ARTICLE','CERTIFICATION')),
    title VARCHAR(150) NOT NULL,
    description TEXT,
    url VARCHAR(500),
    repository_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    website VARCHAR(500),
    logo_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    url VARCHAR(500),
    status VARCHAR(30) NOT NULL DEFAULT 'INTERESTED' CHECK (status IN ('INTERESTED','APPLIED','INTERVIEW','TECHNICAL_INTERVIEW','OFFER','REJECTED','WITHDRAWN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE job_skill (
    job_id BIGINT NOT NULL REFERENCES job(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    relevance SMALLINT NOT NULL CHECK (relevance BETWEEN 1 AND 10),
    required BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    PRIMARY KEY (job_id, skill_id)
);
CREATE TABLE profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES job(id) ON DELETE CASCADE,
    slug VARCHAR(150) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    headline VARCHAR(300),
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE profile_skill (
    profile_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    PRIMARY KEY (profile_id, skill_id)
);
CREATE INDEX idx_skill_category_id ON skill(category_id);
CREATE INDEX idx_evidence_skill_id ON evidence(skill_id);
CREATE INDEX idx_job_company_id ON job(company_id);
CREATE INDEX idx_job_status ON job(status);
CREATE INDEX idx_job_skill_skill_id ON job_skill(skill_id);
CREATE INDEX idx_profile_job_id ON profile(job_id);
CREATE INDEX idx_profile_skill_skill_id ON profile_skill(skill_id);

CREATE FUNCTION set_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_skill_updated_at BEFORE UPDATE ON skill
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_profile_updated_at BEFORE UPDATE ON profile
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
